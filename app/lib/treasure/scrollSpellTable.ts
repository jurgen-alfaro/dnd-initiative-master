import { COPPER_PER_COIN, poToCp } from "./coins";

/**
 * DMG 3.5 tables 7-24 ("Rollos de pergamino (conjuros arcanos)") and 7-25
 * ("Rollos de pergamino (conjuros divinos)"), one list per spell level 0-9.
 *
 * Each row is copied as the book prints it, "d%|Conjuro|Precio de mercado",
 * so it can be checked against the captures line by line. Prices marked with
 * a footnote in the book (XP or material costs assumed) are kept as printed.
 */

export type ScrollSpellRow = { upTo: number; name: string; valueCp: number };

/** "12 po 5 pp" → 1250, "1.000 po" → 100000 (the book's "." groups thousands). */
function parsePrice(text: string): number {
  const match = /^(\d{1,3}(?:\.\d{3})*) po(?: (\d) pp)?$/.exec(text);
  if (!match) throw new Error(`Unreadable scroll price "${text}"`);
  return (
    poToCp(Number(match[1].replaceAll(".", ""))) +
    Number(match[2] ?? 0) * COPPER_PER_COIN.pp
  );
}

/**
 * Turns the printed rows of one level into d% rows, failing at load if a
 * range leaves a gap, overlaps the previous one or does not end at 100.
 */
function parseLevel(lines: readonly string[]): readonly ScrollSpellRow[] {
  let previous = 0;
  const rows = lines.map((line) => {
    const [range, name, price] = line.split("|");
    const match = /^(\d+)(?:-(\d+))?$/.exec(range);
    if (!match || !name || !price) throw new Error(`Unreadable scroll row "${line}"`);
    const low = Number(match[1]);
    const upTo = Number(match[2] ?? match[1]);
    if (low !== previous + 1 || upTo < low) {
      throw new Error(`Scroll row "${line}" does not follow ${previous}`);
    }
    previous = upTo;
    return { upTo, name, valueCp: parsePrice(price) };
  });
  if (previous !== 100) throw new Error(`Scroll table ends at ${previous}, not 100`);
  return rows;
}

