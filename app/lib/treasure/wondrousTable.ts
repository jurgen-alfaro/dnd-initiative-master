/** [name, price in po] of one d% row; a third item marks a bag of tricks. */
type Entry = readonly [name: string, po: number, bag?: BagColor];

/** Each table of the book gives one object per roll, so row N is roll N. */
const rows = (entries: readonly Entry[]): readonly WondrousRow[] =>
  entries.map(([name, po, bag], index) => ({
    upTo: index + 1,
    name,
    valueCp: po * 100,
    ...(bag && { bag }),
  }));

